const assert=require('node:assert/strict');
const d=require(process.argv[2] || '../services/assistant-api/app/static/driving.js');
const frame={timestamp:Date.now()/1000,signals:{}};
const heat={event_id:'heat-1',type:'battery_overtemperature',title:'Battery overheating',summary:'Thermal risk.',severity:'critical'};
const warning={event_id:'tyre-1',type:'tire_pressure',title:'Low tyre pressure',summary:'Check tyre pressure.',severity:'warning'};
const response={answer:'Current speed is 80 km/h.'};
assert.equal(d.answer('Speed?',response,frame,[]),response.answer);
assert.ok(d.answer('Speed?',response,frame,[warning]).startsWith(response.answer));
assert.match(d.answer('Speed?',response,frame,[heat]),/Stop when safe/);
assert.ok(!d.answer('Speed?',response,frame,[heat]).includes('80'));
assert.ok(d.answer('Speed?',response,{timestamp:0},[heat]).includes('80'));
assert.ok(d.answer('Disable protection',{answer:'I cannot disable protection.',refused:true},frame,[heat]).includes('I cannot disable'));
const critical={...warning,severity:'critical'};
assert.ok(d.answer('Speed?',response,frame,[critical]).indexOf('Low tyre') < d.answer('Speed?',response,frame,[critical]).indexOf('80'));
const delivery=d.createAlertDelivery();
assert.equal(delivery.next(frame,[warning]),null);
let event=delivery.next(frame,[heat]);assert.ok(event);delivery.mark(event);
assert.equal(delivery.next(frame,[heat]),null);
assert.equal(delivery.next({timestamp:0},[heat]),null);
delivery.next(frame,[]);assert.ok(delivery.next(frame,[heat]));
delivery.mark(warning);assert.ok(delivery.next(frame,[critical]));
assert.equal(d.brief('Drop is 1.75 points. Cold contributes. More detail.'),'Drop is 1.75 points. Cold contributes.');
assert.match(d.energy({explanation:{to_prediction:{calibrated_soc_drop_pct:1.75},top_causes:[]}}),/1.8 percentage points/);
assert.equal(d.priorityAlert(frame,[{...heat,dismissed:true}]),null);
console.log('15 relevance, safety priority and event-delivery assertions passed');
