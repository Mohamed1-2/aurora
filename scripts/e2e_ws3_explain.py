"""WS3 end-to-end demo — deterministic SOC-drop explanation reaches the driver.

Driver asks "why is my SOC dropping so fast?" while on a real (simulated) trip.
The stack the driver's car actually talks to:

  assistant  (in-process, real AssistantPipeline it runs in production)
      |  auto-fetch: POST /api/prediction/explain-from-telemetry  (raw 10 Hz frames)
      v
  telemetry-simulator  (REAL uvicorn on :8101 — bins, freezes features, computes
                        physics + SHAP, returns PredictionExplanation, never raises)
      |
      v  block injected into prompt (## PREDICTION EXPLANATION)
  llm-gateway  (REAL uvicorn on :8092 — always a FRESH instance of the current
                mock provider, quote-only "why" handler)
      |
      v
  AURORA natural-language answer, every figure quoted from the block

Frame delivery is the ONE deterministic stand-in: the eval harness treats the
WS push the same way (replay). Instead of waiting 10 minutes of wall-clock at
10 Hz, we feed the exact 10 Hz frame payloads the simulator's WS would emit,
generated by the simulator's own vehicle model (two 300 s trip phases:
50 km/h city -> 125 km/h highway, so the delta is real and positive).

Run from the repo root:
    .venv/bin/python scripts/e2e_ws3_explain.py
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
VENV_PY = ROOT / ".venv" / "bin" / "python"

SIM_PORT = 8101
GATEWAY_PORT = 8092  # dedicated: always a fresh instance of the CURRENT mock provider

DATASET_WINDOW_S = 300.0
HZ = 10.0
WINDOW_FRAMES = int(DATASET_WINDOW_S * HZ)
PHASES = [(300.0, 50.0), (300.0, 125.0)]  # (seconds, target speed kph) -> highway leg last
TOTAL_FRAMES = int(sum(s for s, _ in PHASES) * HZ)

SIM_DIR = ROOT / "services" / "telemetry-simulator"
GATEWAY_DIR = ROOT / "services" / "llm-gateway"
ASSISTANT_DIR = ROOT / "services" / "assistant-api"


def _health(path: str) -> bool:
    try:
        return httpx.get(path, timeout=2.0).status_code == 200
    except Exception:  # noqa: BLE001
        return False


def _wait(path: str, name: str, timeout: float = 25.0) -> None:
    due = time.time() + timeout
    while time.time() < due:
        if _health(path):
            print(f"[ready] {name}")
            return
        time.sleep(0.3)
    raise SystemExit(f"{name} did not become ready in {timeout}s ({path})")


def _start_service(dir: Path, port: int) -> subprocess.Popen | None:
    if _health(f"http://127.0.0.1:{port}/healthz"):
        print(f"[skip] already running on :{port} — using it")
        return None
    log = ROOT / "artifacts" / "logs" / f"e2e_ws3_{port}.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    p = subprocess.Popen(
        [str(VENV_PY), "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", str(port), "--log-level", "warning"],
        cwd=str(dir),
        stdout=open(log, "ab"),
        stderr=subprocess.STDOUT,
    )
    _wait(f"http://127.0.0.1:{port}/healthz", f"service :{port}", timeout=30.0)
    return p


def _banner(title: str) -> None:
    print(f"\n{'=' * 74}\n  {title}\n{'=' * 74}")


def _generate_frames() -> list[dict]:
    """Use the simulator's OWN vehicle model to emit the exact WS frame payloads."""
    sys.path.insert(0, str(SIM_DIR))
    sys.path.insert(0, str(ROOT / "services"))
    from app.config import settings as sim_cfg  # type: ignore[import-not-found]
    from app.engine.vehicle_model import VehicleModel  # type: ignore[import-not-found]

    model = VehicleModel(sim_cfg.vehicle_id, seed=sim_cfg.seed)
    model.configure_trip(
        destination_km=26.0,
        cabin_set_temp_c=22.0,
        ambient_temp_c=10.0,
        speed_profile_kph=[s for _, s in PHASES],
        segment_s=PHASES[0][0],
    )
    frames: list[dict] = []
    for i in range(TOTAL_FRAMES):
        frames.append(model.tick(1.0 / HZ))
    return frames


def _load_assistant():
    """Load the assistant package fresh (isolates it from the sim's ``app``)."""
    for _mod in [k for k in list(sys.modules) if k == "app" or k.startswith("app.")]:
        sys.modules.pop(_mod, None)
    sys.path.insert(0, str(ASSISTANT_DIR))
    import importlib

    service = importlib.import_module("app.core.service")
    ingest = importlib.import_module("app.telemetry.ingest")
    prompt = importlib.import_module("app.core.prompt")
    intents = importlib.import_module("app.core.intents")
    schemas = importlib.import_module("vehicle_ai.schemas")
    return service, ingest, prompt, intents, schemas


def _render_block(prompt_mod, pipe, question: str, intents: list[str], expl) -> str:
    from vehicle_ai.schemas import Grounding

    grounding = Grounding(telemetry=pipe.telemetry.grounding())
    msgs = prompt_mod.build_messages(question, grounding, intents=intents, explanation=expl)
    content = msgs[-1].content
    marker = "## PREDICTION EXPLANATION"
    return content[content.find(marker):] if marker in content else ""


def pipe_intents(question: str) -> list[str]:
    import app.core.intents as _i  # noqa: PLC0415 (bound quickly; reloaded each call)
    return _i.detect(question)


def main() -> int:
    os.environ.setdefault("AURORA_ASSISTANT_GATEWAY_URL", f"http://localhost:{GATEWAY_PORT}")
    os.environ.setdefault("AURORA_ASSISTANT_TELEMETRY_HTTP", f"http://localhost:{SIM_PORT}")
    os.environ.setdefault("AURORA_ASSISTANT_RAG_URL", "")

    _banner("AURORA · WS3 'Why?' — deterministic SOC-drop explanation, end to end")
    print(f"driver drive: {' -> '.join(f'{s:.0f}s @ {v:.0f} km/h' for s, v in PHASES)}")
    print(f"telemetry:    :{SIM_PORT}  gateway: :{GATEWAY_PORT}  frames: {TOTAL_FRAMES} @ {HZ:.0f} Hz")

    sim = _start_service(SIM_DIR, SIM_PORT)
    gateway = _start_service(GATEWAY_DIR, GATEWAY_PORT)
    sim_port = sim and sim.poll() is None

    try:
        frames = _generate_frames()
        print(f"[frames] generated {len(frames)} via sim vehicle model; "
              f"to = last {WINDOW_FRAMES} (highway {PHASES[-1][1]:.0f} km/h), from = preceding city leg")

        service, ingest_mod, prompt_mod, _, schemas = _load_assistant()
        telemetry = ingest_mod.TelemetryIngest(ws_url="", replay_path="", window_seconds=10.0, max_frames=TOTAL_FRAMES + 500)
        telemetry.frames.extend(frames)
        telemetry.source = "demo"
        pipe = service.AssistantPipeline(telemetry)

        question = "Why is my SOC dropping so fast right now?"
        intents = pipe_intents(question)

        async def _run():
            expl = await pipe._fetch_prediction_explanation()
            block = _render_block(prompt_mod, pipe, question, intents, expl)
            resp = await pipe.ask(schemas.AssistantRequest(question=question, vehicle_id="ORION-X-DEMO-01", use_rag=False))
            return expl, block, resp

        import asyncio

        expl, block, resp = asyncio.run(_run())  # one loop: one httpx client, one connection pool

        _banner("1 · Auto-fetch: raw frames -> deterministic PREDICTION EXPLANATION")
        if expl is None or expl.status != "active":
            print("FAIL: explanation not fetched (auto-fetch should never raise, this should not happen)")
            return 1
        print(f"  status         : {expl.status}   shape: {expl.shape}")
        print(f"  to window      : {expl.to_prediction.calibrated_soc_drop_pct:.3f} SOC pts "
              f"(physics {expl.to_prediction.physics_soc_drop_pct:.3f} + ML residual {expl.to_prediction.ml_residual_pct:.3f})")
        if expl.from_prediction is not None:
            print(f"  from window    : {expl.from_prediction.calibrated_soc_drop_pct:.3f} SOC pts  "
                  f"delta_matches={expl.identity_checks.delta_matches}")
        print(f"  identity checks: physics_sum_matches={expl.identity_checks.physics_sum_matches} "
              f"ml_sum_matches={expl.identity_checks.ml_sum_matches} blend_matches={expl.identity_checks.blend_matches}")
        print(f"  top causes     : {[c.label for c in expl.top_causes]}")

        print("\n  deterministic block injected into the prompt:\n")
        for line in block.splitlines(keepends=True):
            print("    | " + line.rstrip())

        _banner("2 · Driver -> AURORA")
        print(f"  intents: {resp.intents}   provider: {resp.provider}/{resp.model}   latency: {resp.latency_ms} ms\n")
        print("  AURORA:")
        for para in resp.answer.split("\n"):
            if not para.strip():
                continue
            print("    " + para)
        print()

        ok_intents = "why_prediction" in resp.intents
        ok_quotes = "Predicted SOC drop" in resp.answer or "deterministic" in resp.answer.lower() or "prediction" in resp.answer.lower()
        print("=" * 74)
        print(f"  WS3 DEMO: intents=[{','.join(resp.intents)}]  explanation=active  quote_only={'OK' if ok_quotes else 'CHECK'}")
        print("  every cause/number above was computed in code and quoted from the")
        print("  deterministic block — the LLM/provider only styled the wording. FREEZE WS3.")
        return 0
    finally:
        if sim is not None and sim.poll() is None:
            sim.terminate()
        if gateway is not None and gateway.poll() is None:
            gateway.terminate()


if __name__ == "__main__":
    raise SystemExit(main())